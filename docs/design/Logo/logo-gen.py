import math, sys, json
def bez(pts, t):
    # general bezier via de casteljau
    p = [list(q) for q in pts]
    while len(p) > 1:
        p = [[a[0]+(b[0]-a[0])*t, a[1]+(b[1]-a[1])*t] for a, b in zip(p, p[1:])]
    return p[0]
def width(prof, t):
    # prof: list of (t, w) keyframes, smoothstep between
    for (t0, w0), (t1, w1) in zip(prof, prof[1:]):
        if t0 <= t <= t1:
            u = (t - t0) / (t1 - t0) if t1 > t0 else 0
            u = u*u*(3-2*u)
            return w0 + (w1-w0)*u
    return prof[-1][1]
def stroke(segs, prof, n=40):
    # segs: list of bezier control-point lists, chained
    pts = []
    for i, s in enumerate(segs):
        for k in range(n + 1):
            if i and k == 0: continue
            pts.append(bez(s, k / n))
    N = len(pts); L = []; R = []
    for i, p in enumerate(pts):
        a = pts[max(i-1, 0)]; b = pts[min(i+1, N-1)]
        dx, dy = b[0]-a[0], b[1]-a[1]; d = math.hypot(dx, dy) or 1
        nx, ny = -dy/d, dx/d
        w = width(prof, i/(N-1)) / 2
        L.append((p[0]+nx*w, p[1]+ny*w)); R.append((p[0]-nx*w, p[1]-ny*w))
    def cap(c, a, b, fwd):
        # 从 a 绕过 fwd 方向到 b 的半圆
        r = math.hypot(a[0]-c[0], a[1]-c[1])
        a0 = math.atan2(a[1]-c[1], a[0]-c[0]); a1 = math.atan2(b[1]-c[1], b[0]-c[0])
        mid = math.atan2(fwd[1], fwd[0])
        out = []
        for s in (1, -1):
            span = (a1 - a0) % (2*math.pi) if s == 1 else -((a0 - a1) % (2*math.pi))
            m = a0 + span/2
            if math.cos(m - mid) > 0:
                out = [(c[0]+r*math.cos(a0+span*k/10), c[1]+r*math.sin(a0+span*k/10)) for k in range(1, 10)]
        return out
    f = lambda q: f"{q[0]:.2f} {q[1]:.2f}"
    e = pts[-1]; e0 = pts[-2]; s = pts[0]; s1 = pts[1]
    ring = L + cap(e, L[-1], R[-1], (e[0]-e0[0], e[1]-e0[1])) + list(reversed(R)) + cap(s, R[0], L[0], (s[0]-s1[0], s[1]-s1[1]))
    d = "M" + "L".join(f(q) for q in ring) + "Z"
    return d
